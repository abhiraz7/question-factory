// One-off generator: extracts the actual hard-fail validator functions from
// notes-factory/index.html (vCheckPipelineArtifacts, vCheckTagBalance,
// vCheckImageAlt, vCheckParagraphs, vCheckLinks, vCheckDuplicateIds,
// vCheckBareH3, vCheckScriptTags, vCheckCitations, vCheckToc, vCheckAdSlots,
// vCheckTitle, vCheckMeta, vCheckSlug, vCheckH1, vCheckFirst100Words,
// vRunChecks, plus their small helpers) into a standalone Node module backed by jsdom instead
// of a real browser DOMParser — so the automated pipeline is checked against
// the EXACT SAME gate the manual tool's "Run validation" button uses, not a
// separately-maintained (and driftable) re-implementation. Re-run this any
// time notes-factory/index.html's validators change.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..', '..', '..');
const src = fs.readFileSync(path.join(REPO_ROOT, 'notes-factory', 'index.html'), 'utf8');

function extractFn(name) {
  const re = new RegExp('function ' + name + '\\(');
  const start = src.search(re);
  if (start < 0) throw new Error('function not found: ' + name);
  let i = src.indexOf('{', start);
  let depth = 0;
  for (; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}') { depth--; if (depth === 0) { i++; break; } }
  }
  return src.slice(start, i);
}
function extractConst(name) {
  const re = new RegExp('const ' + name + ' = ');
  const start = src.search(re);
  if (start < 0) throw new Error('const not found: ' + name);
  const semiIdx = src.indexOf(';', start);
  return src.slice(start, semiIdx + 1);
}

const names = [
  'vParseBody', 'vProseText', 'vWordCount', 'vNormalize', 'vCountKeyphrase',
  'vCheckImageAlt', 'vCheckParagraphs', 'vCheckLinks', 'vCheckDuplicateIds',
  'vCheckBareH3', 'vCheckScriptTags', 'vCheckCitations', 'vCheckToc',
  'vCheckAdSlots', 'vCheckTitle', 'vCheckMeta', 'vCheckSlug', 'vCheckH1',
  'vCheckFirst100Words', 'vCheckPipelineArtifacts', 'vCheckTagBalance', 'vRunChecks'
];

let out = `// AUTO-GENERATED by gen-validators-notes.mjs from notes-factory/index.html.
// Do not hand-edit — re-run the generator instead so this never drifts from
// the manual browser tool's actual "Run validation" gate.
import { JSDOM } from 'jsdom';
const DOMParser = new JSDOM('').window.DOMParser;
const TARGET_SITE_HOST = 'examnotespdf.in';
let state = { hindiPercent: 70 };
export function setHindiPercent(p){ state.hindiPercent = p; }

`;
out += extractConst('REFERENCE_SOURCES_GENERAL') + '\n\n'; // unused here, harmless
for (const n of names) out += extractFn(n) + '\n\n';
out += 'export { vRunChecks, vParseBody, vCheckPipelineArtifacts };\n';

fs.writeFileSync(path.join(__dirname, 'validators-notes.mjs'), out);
console.log('wrote validators-notes.mjs');
