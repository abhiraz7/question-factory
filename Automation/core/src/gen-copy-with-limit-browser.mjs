// Generator for a browser-consumable mirror of copy-with-limit.mjs, same
// mechanical approach as gen-flavour-engine-browser.mjs (strip `export `,
// wrap in an IIFE that assigns to `global.CopyWithLimit`).
//
// Writes to shared/copy-with-limit.js -- the three browser tools load this
// directly (same convention as shared/flavour-engine.js). See
// notes-factory/index.html's copy-button wiring for the one live call site.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..', '..', '..');
const src = fs.readFileSync(path.join(__dirname, 'copy-with-limit.mjs'), 'utf8');

const body = src.replace(/^export /gm, '');

const out = `// AUTO-GENERATED by gen-copy-with-limit-browser.mjs from
// Automation/core/src/copy-with-limit.mjs (the canonical ESM source) -- do
// not hand-edit this file, re-run the generator instead.
// Exposes window.CopyWithLimit = { MAX_COPY_CHARS, defaultMarker, splitIntoChunks, copyWithLimit, copyChunkToClipboard };
(function(global){
${body}
global.CopyWithLimit = { MAX_COPY_CHARS, defaultMarker, splitIntoChunks, copyWithLimit, copyChunkToClipboard };
})(typeof window !== 'undefined' ? window : this);
`;

const outDir = path.join(REPO_ROOT, 'shared');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'copy-with-limit.js'), out);
console.log('wrote shared/copy-with-limit.js');
