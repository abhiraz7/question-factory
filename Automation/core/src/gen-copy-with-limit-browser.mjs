// Generator for a browser-consumable mirror of copy-with-limit.mjs, same
// mechanical approach as gen-flavour-engine-browser.mjs (strip `export `,
// wrap in an IIFE that assigns to `global.CopyWithLimit`).
//
// DELIBERATELY WRITES TO A DRAFT PATH, NOT shared/: this task's boundaries
// forbid creating/touching anything a live page would load, and shared/ is
// exactly that (notes-factory/index.html etc. load shared/*.js directly).
// Output goes to Automation/core/output/copy-with-limit.browser-draft.js
// instead — a human should review it, then either (a) change outDir below
// to '../../shared' and re-run, or (b) copy the file there by hand, once
// they are ready to wire Phase 12 into the live copy buttons (see Phase 11
// note in this session's progress report).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..', '..', '..');
const src = fs.readFileSync(path.join(__dirname, 'copy-with-limit.mjs'), 'utf8');

const body = src.replace(/^export /gm, '');

const out = `// DRAFT — NOT WIRED IN, NOT shared/copy-with-limit.js.
// Generated by gen-copy-with-limit-browser.mjs from
// Automation/core/src/copy-with-limit.mjs (the canonical ESM source) —
// do not hand-edit this file, re-run the generator instead.
//
// This is sitting in Automation/core/output/ on purpose, not shared/: no
// live page loads it from here. A human must deliberately move/regenerate
// it into shared/copy-with-limit.js AND wire it into notes-factory/
// index.html's (and long-post-factory's / update-factory's) actual copy
// buttons before it does anything live — see this session's
// EDITORIAL_INTELLIGENCE_PROGRESS_REPORT.md, Phase 12 section.
// Exposes window.CopyWithLimit = { MAX_COPY_CHARS, defaultMarker, splitIntoChunks, copyWithLimit, copyChunkToClipboard }.
(function(global){
${body}
global.CopyWithLimit = { MAX_COPY_CHARS, defaultMarker, splitIntoChunks, copyWithLimit, copyChunkToClipboard };
})(typeof window !== 'undefined' ? window : this);
`;

const outDir = path.join(REPO_ROOT, 'Automation', 'core', 'output');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'copy-with-limit.browser-draft.js'), out);
console.log('wrote Automation/core/output/copy-with-limit.browser-draft.js (DRAFT — not shared/, not wired in)');
